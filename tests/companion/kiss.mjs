import assert from 'node:assert/strict';
import { KissDecoder, kissFrame, ax25, decodeAx25, position, message, hex } from '../../companion/src/kiss.mjs';
const decode = bytes => {
    const parser = new KissDecoder();
    return [...bytes].map(byte => parser.feed(byte)).filter(Boolean);
};
assert.equal(hex(kissFrame(Uint8Array.of(0xc0, 0xdb, 1))), 'c0 00 db dc db dd 01 c0');
assert.deepEqual(decode(kissFrame(Uint8Array.of(0xc0, 0xdb, 1)))[0].payload, Uint8Array.of(0xc0, 0xdb, 1));
assert.equal(decode(Uint8Array.of(0xc0, 0, 0xdb, 0, 0xc0)).length, 0);
assert.equal(decode(Uint8Array.of(0xc0, 0, 0xdb, 0xc0)).length, 0);
assert.equal(decode(Uint8Array.from([0xc0, 0, ...new Array(331).fill(1), 0xc0, 0, 2, 0xc0])).length, 1);
assert.equal(decode(kissFrame(new Uint8Array(330)))[0].payload.length, 330);
assert.throws(() => kissFrame(new Uint8Array(331)));
// Frozen, hand-derived AX.25 UI command header, not generated by the codec under test.
const expected = '82 a0 a4 a6 40 40 e0 9c 60 86 82 98 98 63 03 f0 48 69';
const packet = ax25({ destination: 'APRS', source: 'N0CALL-1', payload: 'Hi' });
assert.equal(hex(packet), expected);
assert.deepEqual(decodeAx25(packet), { destination: 'APRS', source: 'N0CALL-1', path: [],
    control: 3, pid: 240, payload: Uint8Array.of(72, 105) });
const routed = ax25({ destination: 'APRS', source: 'N0CALL', path: 'WIDE1-1,WIDE2-2', payload: '' });
assert.equal(routed[13], 0x60);
assert.equal(routed[20], 0x62);
assert.equal(routed[27], 0x65);
for (let length = 0; length < 16; length++) {
    assert.throws(() => decodeAx25(packet.slice(0, length)));
}
assert.throws(() => ax25({ destination: 'APRS', source: 'N0CALL-16', payload: '' }));
assert.throws(() => ax25({ destination: 'APRS', source: 'n0call', payload: '' }));
assert.throws(() => ax25({ destination: 'APRS', source: 'N0CALL', path: 'A,'.repeat(8) + 'B', payload: '' }));
assert.equal(position({ latitude: 49.058333333, longitude: -72.029166667, symbol: '-' }), '!4903.50N/07201.75W-');
assert.equal(position({ latitude: 89.9999999, longitude: -179.9999999 }), '!9000.00N/18000.00W>');
assert.equal(position({ latitude: -90, longitude: 180 }), '!9000.00S/18000.00E>');
for (const latitude of ['', null, '0x10', NaN, Infinity, 90.0001]) {
    assert.throws(() => position({ latitude, longitude: 0 }));
}
assert.throws(() => position({ latitude: 0, longitude: 0, comment: 'a'.repeat(44) }));
assert.throws(() => position({ latitude: 0, longitude: 0, comment: 'ä' }));
assert.equal(message({ addressee: 'N0CALL', text: 'Hello' }), ':N0CALL   :Hello');
assert.equal(message({ addressee: 'N0CALL-15', text: 'x'.repeat(67) }).length, 78);
for (const text of ['', 'x'.repeat(68), 'hello|', 'hello~', 'hello{', 'ä', '\n']) {
    assert.throws(() => message({ addressee: 'N0CALL', text }));
}
assert.throws(() => message({ addressee: 'ABCDEFGHIJ', text: 'hi' }));
console.log('KISS / AX.25 / APRS checks passed');
