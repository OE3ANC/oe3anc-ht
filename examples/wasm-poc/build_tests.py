"""Build three import-free DSP compatibility probes and their firmware resource header."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clang', default=str(ROOT / '.deps/ci/emsdk/upstream/bin/clang'))
    parser.add_argument('--output', type=Path, default=ROOT / 'build/wasm-tests')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    header = ['// Generated by examples/wasm-poc/build_tests.py; do not edit.', '#pragma once']
    manifest = []
    for index, name in enumerate(('arithmetic', 'pcm_gain', 'checksum'), 1):
        output = args.output / (name + '.wasm')
        subprocess.run([
            args.clang, '--target=wasm32', '-mcpu=mvp', '-std=c11', '-O2',
            '-Wall', '-Wextra', '-Werror', '-nostdlib', '-fno-builtin',
            f'-DHT_TEST_ID={index}', '-Wl,--no-entry', '-Wl,--export=main',
            '-Wl,--export=get_output_count', '-Wl,--export-memory',
            '-Wl,--initial-memory=65536', '-Wl,--max-memory=65536',
            '-Wl,-z,stack-size=8192', '-Wl,--strip-all',
            str(HERE / 'test_program.c'), '-o', str(output),
        ], check=True)
        data = output.read_bytes()
        header.append(f'static const unsigned char wasm_test_{index}[] = {{')
        for pos in range(0, len(data), 16):
            header.append('    ' + ', '.join(f'0x{x:02x}' for x in data[pos:pos + 16]) + ',')
        header.append('};')
        manifest.append({'file': output.name, 'bytes': len(data), 'expected': index * 11,
                         'sha256': hashlib.sha256(data).hexdigest()})
    (args.output / 'wasm_programs.h').write_text('\n'.join(header) + '\n')
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    main()
